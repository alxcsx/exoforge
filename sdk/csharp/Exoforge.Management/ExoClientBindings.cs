using System;
using System.IO;
using System.Linq;

namespace Exoforge.Management;

public enum ClientBindingsState
{
    /// <summary>The generated client file is there and no extension manifest is newer.</summary>
    Current,

    /// <summary>No generated client file (a fresh clone that has not synced yet).</summary>
    Missing,

    /// <summary>An extension was built after the client was generated, so the client may lack its newest services.</summary>
    Stale,
}

/// <summary>
/// What state the Unity-side client file (<c>Assets/Exoforge/Generated/ExoforgeServices.g.cs</c>) is in. That file is
/// committed or regenerated by an explicit action, never made on load, so the editor reads this and says so in a banner
/// instead of generating or throwing. It looks at timestamps only, and never throws.
/// </summary>
public static class ExoClientBindings
{
    public static ClientBindingsState Check(ExoWorkspace workspace, string generatedPath)
    {
        try
        {
            if (!File.Exists(generatedPath) || new FileInfo(generatedPath).Length == 0) return ClientBindingsState.Missing;

            DateTime generated = File.GetLastWriteTimeUtc(generatedPath);
            bool newer = workspace.IncludedExtensions()
                .Select(name => Path.Combine(workspace.ExtensionsPath, name, "manifest.json"))
                .Any(manifest => File.Exists(manifest) && File.GetLastWriteTimeUtc(manifest) > generated);
            return newer ? ClientBindingsState.Stale : ClientBindingsState.Current;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return ClientBindingsState.Current;
        }
    }

    /// <summary>The banner text for a state, or null when there is nothing to say.</summary>
    public static string? Message(ClientBindingsState state, string generatedPath) => state switch
    {
        ClientBindingsState.Missing =>
            $"The C# client ({generatedPath}) has not been generated. Press Sync Client in the Extensions tab (or run `exo sync`); it is never made automatically.",
        ClientBindingsState.Stale =>
            $"The C# client ({generatedPath}) is older than an extension you built. Press Sync Client to update it.",
        _ => null,
    };

    /// <summary>
    /// A workspace whose extensions folder sits where Unity compiles C# (under the project's Assets or Packages).
    /// Returns the reason, or null when the extensions are outside Unity's reach. Extensions belong beside the project
    /// (<c>Exoforge/extensions</c>, or a shared folder), never inside <c>Assets</c>.
    /// </summary>
    public static string? ExtensionsInsideUnityCompile(ExoWorkspace workspace)
    {
        try
        {
            string extensions = Path.GetFullPath(workspace.ExtensionsPath).Replace('\\', '/').TrimEnd('/') + "/";
            var dir = new DirectoryInfo(extensions);
            while (dir != null)
            {
                if (Directory.Exists(Path.Combine(dir.FullName, "ProjectSettings")) && Directory.Exists(Path.Combine(dir.FullName, "Assets")))
                {
                    string root = dir.FullName.Replace('\\', '/').TrimEnd('/') + "/";
                    foreach (string folder in new[] { "Assets", "Packages" })
                    {
                        if (extensions.StartsWith(root + folder + "/", StringComparison.OrdinalIgnoreCase))
                        {
                            return $"The extensions folder {workspace.ExtensionsPath} is inside the Unity project's {folder}/, where Unity would compile extension code. " +
                                   "Move it beside the project (Exoforge/extensions) and set extensions_dir in exoforge.json.";
                        }
                    }

                    return null;
                }

                dir = dir.Parent;
            }
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or ArgumentException)
        {
        }

        return null;
    }
}
