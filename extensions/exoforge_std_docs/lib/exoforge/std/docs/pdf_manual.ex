defmodule Exoforge.Std.Docs.PdfManual do
  @moduledoc """
  Generates a high-quality, multi-page standalone PDF manual for Exoforge.
  Combines markdown documentation chapters with dynamic cluster API catalog data.
  Outputs a standard PDF 1.4 binary with zero external dependencies.
  """

  alias Exoforge.BuildInfo
  alias Exoforge.Std.Docs

  @page_width 595.28
  @page_height 841.89
  @margin_left 45.0
  @margin_right 45.0
  @usable_width @page_width - @margin_left - @margin_right
  @top_margin 790.0
  @bottom_margin 55.0

  defstruct [
    :version,
    :commit_hash,
    :build_date,
    :pages,
    :current_stream,
    :cursor_y,
    :page_num,
    :in_code_block,
    :code_buffer
  ]

  @doc """
  Generates the complete Exoforge Developer Manual PDF as a binary string.
  """
  def generate do
    version = BuildInfo.version()
    commit_hash = BuildInfo.commit_hash()
    build_date = BuildInfo.build_date()

    chapters = Docs.load_all_chapters()
    catalog = Docs.build_api_catalog()

    state = %__MODULE__{
      version: version,
      commit_hash: commit_hash,
      build_date: build_date,
      pages: [],
      current_stream: [],
      cursor_y: @top_margin,
      page_num: 1,
      in_code_block: false,
      code_buffer: []
    }

    state
    |> render_cover_page()
    |> render_chapters(chapters)
    |> render_api_catalog(catalog)
    |> finalize_pdf()
  end

