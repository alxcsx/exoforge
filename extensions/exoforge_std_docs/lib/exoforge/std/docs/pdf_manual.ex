  ## ---- CHAPTER RENDERING ----

  defp render_chapters(state, chapters) do
    Enum.reduce(chapters, state, fn chapter, acc_state ->
      acc_state
      |> new_page_if_needed(80)
      |> render_chapter_heading(chapter.title)
      |> render_markdown_lines(String.split(chapter.content, ~r/\r?\n/))
    end)
  end

  defp render_chapter_heading(state, title) do
    state = ensure_page_space(state, 60)
    y = state.cursor_y

    heading_cmd = [
      # Purple chapter bar
      "0.486 0.227 0.929 rg\n",
      "45 #{y - 4} 4 22 re f\n",
      "BT /F2 16 Tf 0.09 0.12 0.18 rg 55 #{y} Td (#{escape_text(title)}) Tj ET\n",
      "0.88 0.9 0.94 rg 45 #{y - 12} #{@usable_width} 1 re f\n"
    ]

    %{state | current_stream: [state.current_stream, heading_cmd], cursor_y: y - 32}
  end

  ## ---- MARKDOWN LINES PROCESSOR ----

  defp render_markdown_lines(state, lines) do
    Enum.reduce(lines, state, fn raw_line, acc ->
      line = String.trim_trailing(raw_line)

      cond do
        # Code fence toggle
        String.starts_with?(line, "```") ->
          if acc.in_code_block do
            flush_code_block(acc)
          else
            %{acc | in_code_block: true, code_buffer: []}
          end

        # Accumulating inside code block
        acc.in_code_block ->
          %{acc | code_buffer: acc.code_buffer ++ [line]}

        # Heading 1
        String.starts_with?(line, "# ") ->
          text = String.trim_leading(line, "# ") |> String.trim()
          render_heading(acc, text, 14, 28)

        # Heading 2
        String.starts_with?(line, "## ") ->
          text = String.trim_leading(line, "## ") |> String.trim()
          render_heading(acc, text, 12, 24)

        # Heading 3
        String.starts_with?(line, "### ") ->
          text = String.trim_leading(line, "### ") |> String.trim()
          render_heading(acc, text, 10.5, 20)

        # Horizontal rule
        line in ["---", "***", "___"] ->
          render_horizontal_rule(acc)

        # Bullet list item
        String.starts_with?(line, "- ") or String.starts_with?(line, "* ") ->
          text = String.slice(line, 2..-1//1) |> String.trim()
          render_bullet_item(acc, text)

        # Empty line
        String.trim(line) == "" ->
          %{acc | cursor_y: acc.cursor_y - 8}

        # Regular paragraph line
        true ->
          render_paragraph(acc, line)
      end
    end)
  end

  defp flush_code_block(state) do
    lines = state.code_buffer
    line_count = max(1, length(lines))
    block_height = line_count * 11 + 14

    state = ensure_page_space(state, block_height + 15)
    y = state.cursor_y

    bg_rect = [
      # Light background
      "0.96 0.97 0.99 rg\n",
      "45 #{y - block_height} #{@usable_width} #{block_height} re f\n",
      # Subtle stroke
      "0.85 0.88 0.93 rg 0.75 w\n",
      "45 #{y - block_height} #{@usable_width} #{block_height} re S\n",
      # Purple left accent bar
      "0.486 0.227 0.929 rg\n",
      "45 #{y - block_height} 3 #{block_height} re f\n"
    ]

    code_texts =
      Enum.with_index(lines, 0)
      |> Enum.map(fn {cline, idx} ->
        line_y = y - 13 - idx * 11
        # Truncate lines that exceed printable code width
        safe_line = String.slice(cline, 0, 88)
        "BT /F4 8.5 Tf 0.12 0.14 0.18 rg 54 #{line_y} Td (#{escape_text(safe_line)}) Tj ET\n"
      end)

    %{state | current_stream: [state.current_stream, bg_rect, code_texts], cursor_y: y - block_height - 12, in_code_block: false, code_buffer: []}
  end

  defp render_heading(state, text, font_size, spacing) do
    state = ensure_page_space(state, spacing + 10)
    y = state.cursor_y

    cmd = [
      "BT /F2 #{font_size} Tf 0.1 0.13 0.19 rg 45 #{y} Td (#{escape_text(text)}) Tj ET\n"
    ]

    %{state | current_stream: [state.current_stream, cmd], cursor_y: y - spacing}
  end

  defp render_horizontal_rule(state) do
    state = ensure_page_space(state, 16)
    y = state.cursor_y
    cmd = ["0.88 0.9 0.93 rg 45 #{y} #{@usable_width} 0.75 re f\n"]
    %{state | current_stream: [state.current_stream, cmd], cursor_y: y - 14}
  end

  defp render_bullet_item(state, text) do
    wrapped_lines = wrap_text(text, 78)
    total_height = length(wrapped_lines) * 12 + 4
    state = ensure_page_space(state, total_height)
    y = state.cursor_y

    bullet_marker = [
      "0.486 0.227 0.929 rg\n",
      "52 #{y + 3} 3 3 re f\n"
    ]

    line_cmds =
      Enum.with_index(wrapped_lines, 0)
      |> Enum.map(fn {wline, idx} ->
        ly = y - idx * 12
        "BT /F1 9.5 Tf 0.2 0.23 0.28 rg 62 #{ly} Td (#{escape_text(wline)}) Tj ET\n"
      end)

    %{state | current_stream: [state.current_stream, bullet_marker, line_cmds], cursor_y: y - total_height}
  end

  defp render_paragraph(state, text) do
    wrapped_lines = wrap_text(text, 86)
    total_height = length(wrapped_lines) * 12 + 4
    state = ensure_page_space(state, total_height)
    y = state.cursor_y

    line_cmds =
      Enum.with_index(wrapped_lines, 0)
      |> Enum.map(fn {wline, idx} ->
        ly = y - idx * 12
        "BT /F1 9.5 Tf 0.2 0.23 0.28 rg 45 #{ly} Td (#{escape_text(wline)}) Tj ET\n"
      end)

    %{state | current_stream: [state.current_stream, line_cmds], cursor_y: y - total_height}
  end

  ## ---- DYNAMIC CLUSTER API CATALOG ----

  defp render_api_catalog(state, catalog) do
    state =
      state
      |> new_page_if_needed(120)
      |> render_chapter_heading("Dynamic Cluster API Reference")
      |> render_paragraph(
        "This chapter lists all live services, actions, parameters, scopes, and schemas extracted dynamically from active cluster extensions."
      )

    Enum.reduce(catalog, state, fn svc, acc_svc ->
      acc_svc
      |> ensure_page_space(70)
      |> render_service_header(svc)
      |> render_service_actions(svc.actions)
    end)
  end

  defp render_service_header(state, svc) do
    y = state.cursor_y
    title = "#{svc.title} (:#{svc.name})"

    cmd = [
      # Service badge box
      "0.92 0.94 0.98 rg\n",
      "45 #{y - 18} #{@usable_width} 24 re f\n",
      "0.78 0.82 0.92 rg 1 w\n",
      "45 #{y - 18} #{@usable_width} 24 re S\n",
      "BT /F2 12 Tf 0.15 0.2 0.35 rg 55 #{y - 12} Td (#{escape_text(title)}) Tj ET\n",
      "BT /F3 9 Tf 0.45 0.5 0.6 rg 400 #{y - 12} Td (Extension: #{escape_text(svc.extension_id)}) Tj ET\n"
    ]

    %{state | current_stream: [state.current_stream, cmd], cursor_y: y - 32}
  end

  defp render_service_actions(state, actions) do
    Enum.reduce(actions, state, fn act, acc_act ->
      acc_act
      |> ensure_page_space(65)
      |> render_action_entry(act)
    end)
  end

  defp render_action_entry(state, act) do
    y = state.cursor_y
    sig = ".#{act.name}() [#{act.mode}] — Scope: #{act.scope}"

    action_header = [
      "BT /F5 10 Tf 0.486 0.227 0.929 rg 50 #{y} Td (#{escape_text(sig)}) Tj ET\n",
      "BT /F1 9 Tf 0.3 0.34 0.4 rg 50 #{y - 12} Td (#{escape_text(act.doc)}) Tj ET\n"
    ]

    state = %{state | current_stream: [state.current_stream, action_header], cursor_y: y - 24}

    # Render Parameter Table if params exist
    if act.params != [] do
      render_param_table(state, act.params)
    else
      state
    end
  end

  defp render_param_table(state, params) do
    row_count = length(params)
    table_height = (row_count + 1) * 14 + 6
    state = ensure_page_space(state, table_height + 10)
    y = state.cursor_y

    # Header Row
    header_box = [
      "0.94 0.95 0.97 rg\n",
      "50 #{y - 13} #{@usable_width - 10} 14 re f\n",
      "0.85 0.88 0.92 rg 0.5 w\n",
      "50 #{y - 13} #{@usable_width - 10} 14 re S\n",
      "BT /F2 8 Tf 0.2 0.24 0.3 rg 55 #{y - 9} Td (Parameter) Tj ET\n",
      "BT /F2 8 Tf 0.2 0.24 0.3 rg 165 #{y - 9} Td (Type) Tj ET\n",
      "BT /F2 8 Tf 0.2 0.24 0.3 rg 255 #{y - 9} Td (Requirement) Tj ET\n",
      "BT /F2 8 Tf 0.2 0.24 0.3 rg 335 #{y - 9} Td (Description) Tj ET\n"
    ]

    rows =
      Enum.with_index(params, 0)
      |> Enum.map(fn {p, idx} ->
        ry = y - 13 - (idx + 1) * 14
        bg = if rem(idx, 2) == 1, do: "0.98 0.98 0.99 rg 50 #{ry} #{@usable_width - 10} 14 re f\n", else: ""
        req = if p.optional, do: "Optional", else: "Required"
        doc = p.doc || "—"

        [
          bg,
          "0.88 0.9 0.93 rg 0.5 w 50 #{ry} #{@usable_width - 10} 14 re S\n",
          "BT /F4 8 Tf 0.1 0.1 0.15 rg 55 #{ry + 4} Td (#{escape_text(p.name)}) Tj ET\n",
          "BT /F4 8 Tf 0.3 0.35 0.45 rg 165 #{ry + 4} Td (#{escape_text(p.type)}) Tj ET\n",
          "BT /F1 8 Tf 0.25 0.28 0.35 rg 255 #{ry + 4} Td (#{escape_text(req)}) Tj ET\n",
          "BT /F1 8 Tf 0.4 0.43 0.48 rg 335 #{ry + 4} Td (#{escape_text(String.slice(doc, 0, 42))}) Tj ET\n"
        ]
      end)

    %{state | current_stream: [state.current_stream, header_box, rows], cursor_y: y - table_height - 6}
  end

  ## ---- PAGE FLUSHING & PAGINATION ----

  defp ensure_page_space(state, required_height) do
    if state.cursor_y - required_height < @bottom_margin do
      flush_page(state)
    else
      state
    end
  end

  defp new_page_if_needed(state, min_space) do
    if state.cursor_y - min_space < @bottom_margin do
      flush_page(state)
    else
      state
    end
  end

  defp flush_page(state) do
    page_data = IO.iodata_to_binary(state.current_stream)
    %{state | pages: state.pages ++ [page_data], current_stream: [], cursor_y: @top_margin, page_num: state.page_num + 1}
  end

  ## ---- FINAL PDF ASSEMBLY ----

  defp finalize_pdf(state) do
    # Flush any remaining page data
    state =
      if state.current_stream != [] do
        flush_page(state)
      else
        state
      end

    total_pages = length(state.pages)

    # Decorate pages with running headers & footers (except cover page at index 0)
    decorated_pages =
      Enum.with_index(state.pages, 1)
      |> Enum.map(fn {page_cmd, page_idx} ->
        if page_idx == 1 do
          page_cmd
        else
          header = [
            "BT /F2 8 Tf 0.5 0.54 0.6 rg 45 808 Td (EXOFORGE DEVELOPER MANUAL • CLUSTER ARCHITECTURE) Tj ET\n",
            "0.85 0.88 0.92 rg 45 802 #{@usable_width} 0.5 re f\n"
          ]

          footer = [
            "0.85 0.88 0.92 rg 45 42 #{@usable_width} 0.5 re f\n",
            "BT /F1 8 Tf 0.5 0.54 0.6 rg 45 30 Td (Exoforge Engine • v#{escape_text(state.version)} [#{escape_text(state.commit_hash)}]) Tj ET\n",
            "BT /F2 8 Tf 0.486 0.227 0.929 rg 500 30 Td (Page #{page_idx} of #{total_pages}) Tj ET\n"
          ]

          IO.iodata_to_binary([header, page_cmd, footer])
        end
      end)

    build_pdf_binary(decorated_pages)
  end

  defp build_pdf_binary(pages) do
    total = length(pages)

    # Font dictionary objects: Helvetica, Helvetica-Bold, Helvetica-Oblique, Courier, Courier-Bold
    # Catalog is 1 0 obj, Pages is 2 0 obj, Fonts are 3-7, Pages start at 8, Contents follow
    font_count = 5
    page_obj_start = 3 + font_count
    content_obj_start = page_obj_start + total

    page_kids =
      Enum.map(0..(total - 1), fn idx ->
        "#{page_obj_start + idx} 0 R"
      end)
      |> Enum.join(" ")

    catalog_obj = "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n"
    pages_obj = "2 0 obj\n<< /Type /Pages /Kids [#{page_kids}] /Count #{total} >>\nendobj\n"

    fonts_obj = [
      "3 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n",
      "4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\nendobj\n",
      "5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Oblique >>\nendobj\n",
      "6 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>\nendobj\n",
      "7 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Courier-Bold >>\nendobj\n"
    ]

    font_resources = "<< /F1 3 0 R /F2 4 0 R /F3 5 0 R /F4 6 0 R /F5 7 0 R >>"

    page_objs =
      Enum.map(0..(total - 1), fn idx ->
        content_id = content_obj_start + idx

        "#{page_obj_start + idx} 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 #{@page_width} #{@page_height}] /Resources << /Font #{font_resources} >> /Contents #{content_id} 0 R >>\nendobj\n"
      end)

    content_objs =
      Enum.map(Enum.with_index(pages, 0), fn {cmd_str, idx} ->
        compressed = :zlib.compress(cmd_str)
        len = byte_size(compressed)
        "#{content_obj_start + idx} 0 obj\n<< /Length #{len} /Filter /FlateDecode >>\nstream\n" <> compressed <> "\nendstream\nendobj\n"
      end)

    all_objects = [catalog_obj, pages_obj] ++ fonts_obj ++ page_objs ++ content_objs

    header = "%PDF-1.4\n%\xE2\xE3\xCF\xD3\n"

    {body, offsets} =
      Enum.reduce(all_objects, {header, []}, fn obj, {acc, offs} ->
        off = byte_size(acc)
        {acc <> obj, offs ++ [off]}
      end)

    xref_offset = byte_size(body)

    xref_lines =
      ["0000000000 65535 f \n"] ++
        Enum.map(offsets, fn off ->
          :io_lib.format("~10..0B 00000 n \n", [off]) |> to_string()
        end)

    obj_count = length(all_objects) + 1
    xref = "xref\n0 #{obj_count}\n" <> Enum.join(xref_lines)
    trailer = "trailer\n<< /Size #{obj_count} /Root 1 0 R >>\nstartxref\n#{xref_offset}\n%%EOF\n"

    body <> xref <> trailer
  end

  ## ---- TEXT UTILITIES ----

  defp escape_text(str) when is_binary(str) do
    str
    |> String.replace("\\", "\\\\")
    |> String.replace("(", "\\(")
    |> String.replace(")", "\\)")
    |> sanitize_ascii()
  end

  defp escape_text(other), do: escape_text(to_string(other))

  defp sanitize_ascii(str) do
    # Strip or replace unicode characters not present in Standard 14 font encoding
    str
    |> String.replace(~r/[^\x20-\x7E]/, fn
      "•" -> "*"
      "➔" -> "->"
      "→" -> "->"
      "“" -> "\""
      "”" -> "\""
      "‘" -> "'"
      "’" -> "'"
      "–" -> "-"
      "—" -> "--"
      _ -> " "
    end)
  end

  defp wrap_text(text, max_chars) do
    words = String.split(text, ~r/\s+/)

    Enum.reduce(words, {[], ""}, fn word, {lines, current} ->
      cond do
        current == "" ->
          {lines, word}

        String.length(current) + 1 + String.length(word) <= max_chars ->
          {lines, current <> " " <> word}

        true ->
          {lines ++ [current], word}
      end
    end)
    |> then(fn {lines, current} ->
      if current != "", do: lines ++ [current], else: lines
    end)
  end
end
